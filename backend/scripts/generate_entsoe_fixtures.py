"""Generate SIMULATED ENTSO-E XML documents for offline development.

These files imitate the *structure* of ENTSO-E Transparency Platform responses (A75, A65, A44) so the real
parser can be exercised without a security token. The VALUES ARE SYNTHETIC (deterministic shapes + noise)
and every document carries a SIMULATED marker. They must never be presented as real market data.

Deliberate quality defects (to exercise the quality engine):
- Wind offshore: 8 positions (2 hours) omitted with curveType A01  -> missing intervals
- Prices: curveType A03 with repeated values omitted                -> carry-forward handling
- Biomass: one negative value                                       -> validity rejection
"""
import math
import random
from datetime import UTC, datetime, timedelta
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "fixtures" / "entsoe_simulated"
START = datetime(2026, 11, 13, 23, 0, tzinfo=UTC)
DAYS = 7
SLOTS = DAYS * 96
EIC = "10Y1001A1001A82H"
NS_GL = "urn:iec62325.351:tc57wg16:451-6:generationloaddocument:3:0"
NS_PUB = "urn:iec62325.351:tc57wg16:451-3:publicationdocument:7:3"
rng = random.Random(42)


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%MZ")


def hour_of(i):
    return ((START + timedelta(minutes=15 * i)).hour + 1) % 24  # CET


def solar(i):
    h = hour_of(i) + (i % 4) / 4
    return max(0.0, 9000 * math.sin(math.pi * (h - 8) / 8.5)) if 8 <= h <= 16.5 else 0.0


def wind_on(i):
    return max(500.0, 18000 + 12000 * math.sin(i / 70) + rng.gauss(0, 600))


def wind_off(i):
    return max(100.0, 4200 + 2500 * math.sin(i / 55 + 1) + rng.gauss(0, 200))


def load(i):
    h = hour_of(i)
    return 52000 + 11000 * math.sin(math.pi * (h - 6) / 14) * (1 if 6 <= h <= 20 else 0.2) + rng.gauss(0, 500)


def lignite(i):
    return 9000 + 1500 * math.sin(i / 90) + rng.gauss(0, 150)


def gas(i):
    return max(2000.0, load(i) - solar(i) - wind_on(i) - 20000)


def biomass(i):
    return 4300 + rng.gauss(0, 50)


def pumped_gen(i):
    return 1800.0 if 17 <= hour_of(i) <= 20 else 0.0


def pumped_cons(i):
    return 1400.0 if 1 <= hour_of(i) <= 4 else 0.0


def gl_doc(series_xml, doc_type, process="A16"):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- SIMULATED DATA generated by GridLink scripts/generate_entsoe_fixtures.py. NOT REAL ENTSO-E DATA. -->
<GL_MarketDocument xmlns="{NS_GL}">
  <mRID>SIMULATED-{doc_type}</mRID>
  <revisionNumber>1</revisionNumber>
  <type>{doc_type}</type>
  <process.processType>{process}</process.processType>
  <sender_MarketParticipant.mRID codingScheme="A01">SIMULATED</sender_MarketParticipant.mRID>
  <createdDateTime>2026-11-21T00:00:00Z</createdDateTime>
  <time_Period.timeInterval><start>{iso(START)}</start><end>{iso(START + timedelta(days=DAYS))}</end></time_Period.timeInterval>
{series_xml}
</GL_MarketDocument>
"""


def points(fn, skip=frozenset(), tag="quantity", override=None):
    override = override or {}
    out = []
    for i in range(SLOTS):
        if i in skip:
            continue
        v = override.get(i, fn(i))
        out.append(f"      <Point><position>{i + 1}</position><{tag}>{v:.0f}</{tag}></Point>")
    return "\n".join(out)


def gen_ts(n, psr, fn, direction="in", skip=frozenset(), override=None, curve="A01"):
    zone = f"<{'inBiddingZone' if direction == 'in' else 'outBiddingZone'}_Domain.mRID codingScheme=\"A01\">{EIC}</{'inBiddingZone' if direction == 'in' else 'outBiddingZone'}_Domain.mRID>"
    return f"""  <TimeSeries>
    <mRID>{n}</mRID>
    <businessType>A01</businessType>
    <objectAggregation>A08</objectAggregation>
    {zone}
    <quantity_Measure_Unit.name>MAW</quantity_Measure_Unit.name>
    <curveType>{curve}</curveType>
    <MktPSRType><psrType>{psr}</psrType></MktPSRType>
    <Period>
      <timeInterval><start>{iso(START)}</start><end>{iso(START + timedelta(days=DAYS))}</end></timeInterval>
      <resolution>PT15M</resolution>
{points(fn, skip, override=override)}
    </Period>
  </TimeSeries>"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    gap = frozenset(range(300, 308))
    series = [
        gen_ts(1, "B16", solar), gen_ts(2, "B19", wind_on), gen_ts(3, "B18", wind_off, skip=gap),
        gen_ts(4, "B02", lignite), gen_ts(5, "B04", gas), gen_ts(6, "B01", biomass, override={500: -42}),
        gen_ts(7, "B10", pumped_gen), gen_ts(8, "B10", pumped_cons, direction="out"),
    ]
    (OUT / "A75_generation_DE-LU_simulated.xml").write_text(gl_doc("\n".join(series), "A75"))

    load_ts = f"""  <TimeSeries>
    <mRID>1</mRID>
    <businessType>A04</businessType>
    <objectAggregation>A01</objectAggregation>
    <outBiddingZone_Domain.mRID codingScheme="A01">{EIC}</outBiddingZone_Domain.mRID>
    <quantity_Measure_Unit.name>MAW</quantity_Measure_Unit.name>
    <curveType>A01</curveType>
    <Period>
      <timeInterval><start>{iso(START)}</start><end>{iso(START + timedelta(days=DAYS))}</end></timeInterval>
      <resolution>PT15M</resolution>
{points(load)}
    </Period>
  </TimeSeries>"""
    (OUT / "A65_load_DE-LU_simulated.xml").write_text(gl_doc(load_ts, "A65"))

    # Prices: one Period per delivery day, curveType A03 (repeated values omitted).
    periods = []
    for d in range(DAYS):
        day_start = START + timedelta(days=d)
        pts, last = [], None
        for q in range(96):
            i = d * 96 + q
            h = hour_of(i)
            price = round(85 + 60 * math.sin(math.pi * (h - 6) / 12) - solar(i) / 200 + rng.gauss(0, 4), 2)
            if q % 4:  # keep hourly blocks so A03 compression applies inside each hour
                price = last
            if price != last:
                pts.append(f"      <Point><position>{q + 1}</position><price.amount>{price:.2f}</price.amount></Point>")
            last = price
        periods.append(f"""    <Period>
      <timeInterval><start>{iso(day_start)}</start><end>{iso(day_start + timedelta(days=1))}</end></timeInterval>
      <resolution>PT15M</resolution>
{chr(10).join(pts)}
    </Period>""")
    price_doc = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- SIMULATED DATA generated by GridLink scripts/generate_entsoe_fixtures.py. NOT REAL ENTSO-E DATA. -->
<Publication_MarketDocument xmlns="{NS_PUB}">
  <mRID>SIMULATED-A44</mRID>
  <revisionNumber>1</revisionNumber>
  <type>A44</type>
  <createdDateTime>2026-11-21T00:00:00Z</createdDateTime>
  <period.timeInterval><start>{iso(START)}</start><end>{iso(START + timedelta(days=DAYS))}</end></period.timeInterval>
  <TimeSeries>
    <mRID>1</mRID>
    <businessType>A62</businessType>
    <in_Domain.mRID codingScheme="A01">{EIC}</in_Domain.mRID>
    <out_Domain.mRID codingScheme="A01">{EIC}</out_Domain.mRID>
    <currency_Unit.name>EUR</currency_Unit.name>
    <price_Measure_Unit.name>MWH</price_Measure_Unit.name>
    <curveType>A03</curveType>
{chr(10).join(periods)}
  </TimeSeries>
</Publication_MarketDocument>
"""
    (OUT / "A44_day_ahead_price_DE-LU_simulated.xml").write_text(price_doc)
    print("wrote", sorted(p.name for p in OUT.glob("*.xml")))


if __name__ == "__main__":
    main()
